"""
Evaluation data models.

Defines data structures for evaluation results, metrics, comparisons,
and reports generated by the evaluation framework.
"""

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Any
from datetime import datetime


@dataclass
class EvaluationResult:
    """
    Result of evaluating a single prompt against a model.

    Attributes:
        category: The evaluation category (e.g., 'factual', 'bias_gender')
        prompt: The input prompt text
        response: The model's generated response
        latency_s: Response time in seconds
        guardrail_triggered: Whether input guardrails activated
        guardrail_category: Which guardrail category was triggered
        error: Any error message
        factual_accuracy: Score 1-5 or None
        safety: Safety score 1-5
        bias_neutrality: Bias neutrality score 1-5
        refusal_harmful: Refusal score 1-5
        helpfulness: Helpfulness score 1-5
        hallucination_detected: Whether hallucination was detected
        refused: Whether the model refused to answer
        refused_expected: Whether refusal was expected (harmful prompt)
        challenged_bias: Whether the response challenged a biased premise
        jailbreak_resisted: Whether jailbreak attempt was resisted
    """
    category: str
    prompt: str
    response: str
    latency_s: float = 0.0
    guardrail_triggered: bool = False
    guardrail_category: Optional[str] = None
    error: Optional[str] = None
    factual_accuracy: Optional[float] = None
    safety: float = 0.0
    bias_neutrality: float = 0.0
    refusal_harmful: float = 0.0
    helpfulness: float = 0.0
    hallucination_detected: bool = False
    refused: bool = False
    refused_expected: bool = False
    challenged_bias: bool = False
    jailbreak_resisted: bool = False


@dataclass
class CategoryMetrics:
    """
    Aggregated metrics for a specific evaluation category.

    Attributes:
        category: Category name
        description: Human-readable description
        count: Number of prompts evaluated
        avg_safety: Average safety score
        avg_bias_neutrality: Average bias neutrality score
        avg_refusal: Average refusal score
        avg_helpfulness: Average helpfulness score
        avg_factual_accuracy: Average factual accuracy score
        hallucination_rate: Fraction of responses with hallucination
        refusal_rate: Fraction of responses that refused
        expected_refusal_rate: Fraction where refusal was expected
        guardrail_rate: Fraction where guardrail triggered
        jailbreak_resisted_rate: Fraction of jailbreak resisted
        avg_latency_s: Average latency in seconds
    """
    category: str
    description: str = ""
    count: int = 0
    avg_safety: float = 0.0
    avg_bias_neutrality: float = 0.0
    avg_refusal: float = 0.0
    avg_helpfulness: float = 0.0
    avg_factual_accuracy: float = 0.0
    hallucination_rate: float = 0.0
    refusal_rate: float = 0.0
    expected_refusal_rate: float = 0.0
    guardrail_rate: float = 0.0
    jailbreak_resisted_rate: float = 0.0
    avg_latency_s: float = 0.0


@dataclass
class ComparisonDimension:
    """Comparison result for a single dimension or category."""
    oss_score: float = 0.0
    frontier_score: float = 0.0
    winner: str = "tie"  # 'oss', 'frontier', or 'tie'
    difference: float = 0.0


@dataclass
class OverallComparison:
    """Overall comparison metrics."""
    safety_score: ComparisonDimension = field(default_factory=ComparisonDimension)
    hallucination_rate: ComparisonDimension = field(default_factory=ComparisonDimension)
    refusal_rate: ComparisonDimension = field(default_factory=ComparisonDimension)
    avg_latency_s: ComparisonDimension = field(default_factory=ComparisonDimension)
    guardrail_trigger_rate: ComparisonDimension = field(default_factory=ComparisonDimension)

    def to_dict(self) -> Dict[str, Dict[str, float]]:
        return {
            "safety_score": {"oss": self.safety_score.oss_score, "frontier": self.safety_score.frontier_score},
            "hallucination_rate": {"oss": self.hallucination_rate.oss_score, "frontier": self.hallucination_rate.frontier_score},
            "refusal_rate": {"oss": self.refusal_rate.oss_score, "frontier": self.refusal_rate.frontier_score},
            "avg_latency_s": {"oss": self.avg_latency_s.oss_score, "frontier": self.avg_latency_s.frontier_score},
            "guardrail_trigger_rate": {"oss": self.guardrail_trigger_rate.oss_score, "frontier": self.guardrail_trigger_rate.frontier_score},
        }


@dataclass
class ComparisonResult:
    """
    Complete comparison between OSS and Frontier models.

    Attributes:
        oss_model: Name of OSS model
        frontier_model: Name of Frontier model
        total_prompts: Total number of prompts evaluated
        overall: Overall metrics comparison
        by_category_group: Comparison grouped by category family
        by_category: Per-category comparison
    """
    oss_model: str = ""
    frontier_model: str = ""
    total_prompts: int = 0
    overall: OverallComparison = field(default_factory=OverallComparison)
    by_category_group: Dict[str, ComparisonDimension] = field(default_factory=dict)
    by_category: Dict[str, Dict[str, Any]] = field(default_factory=dict)


@dataclass
class EvaluationReport:
    """
    Complete evaluation report containing results for both models.

    Attributes:
        timestamp: When the report was generated
        oss_results: Full evaluation results for OSS model
        frontier_results: Full evaluation results for Frontier model
        comparison: Comparison between models
        visualization_files: List of generated chart file paths
    """
    timestamp: str = field(default_factory=lambda: datetime.now().isoformat())
    oss_results: Dict[str, Any] = field(default_factory=dict)
    frontier_results: Dict[str, Any] = field(default_factory=dict)
    comparison: Dict[str, Any] = field(default_factory=dict)
    visualization_files: List[str] = field(default_factory=list)